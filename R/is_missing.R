

# ------------ 缺失值判断函数 ------------


# --- is_missing：包括N ---

#' 判断变量中的缺失值，包括N
#'
#' 统一识别R原生缺失值以及数据中常见的字符型缺失值编码。
#' 字符匹配不区分大小写，并自动去除字符串首尾的空格；
#' 字符串中间的空格不会被去除。
#'
#' @param x 需要判断是否缺失的向量。
#'
#' @return 与 `x` 等长的逻辑向量。缺失值返回 `TRUE`，其他值返回 `FALSE`。
#'
#' @details
#' 该函数将以下情况判断为缺失：
#'
#' * R原生缺失值：`NA`，包括数值型 `NaN`；
#' * 空字符串或仅包含空格的字符串；
#' * `"N"`；
#' * `"NA"`；
#' * `"NULL"`；
#' * `"N/A"`；
#' * `"NaN"`；
#' * `"."`；
#' * `"*"`；
#' * `"/"`。
#'
#' 字符型缺失编码不区分大小写，例如 `"n"`、`"na"`、`"null"`
#' 也会被识别为缺失。函数仅去除字符串首尾的空格，例如
#' `" NA "`、`" N "` 和 `". "` 均会被识别为缺失；
#' 字符串中间的空格不会被去除，例如 `"N A"` 不会被识别为 `"NA"`。
#'
#' @examples
#' x <- c(NA, "", " ", "N", "NA", "NULL", "N/A", "NaN", ".", "*", "/", "Yes")
#' is_missing(x)
#'
#' @export
is_missing <- function(x) {

  # 定义字符型缺失编码
  na_strings <- c("", "N", "NA", "NULL", "N/A", "NaN", ".", "*", "/")

  # 统一判断R原生缺失值和字符型缺失编码
  is.na(x) | toupper(trimws(x)) %in% toupper(na_strings)
}


# --- is_miss：不包括N ---

#' 判断变量中的缺失值，不包括N
#'
#' 统一识别R原生缺失值以及数据中常见的字符型缺失值编码，
#' 但不将 `"N"` 作为缺失值处理。
#' 字符匹配不区分大小写，并自动去除字符串首尾的空格；
#' 字符串中间的空格不会被去除。
#'
#' @param x 需要判断是否缺失的向量。
#'
#' @return 与 `x` 等长的逻辑向量。缺失值返回 `TRUE`，其他值返回 `FALSE`。
#'
#' @details
#' 该函数将以下情况判断为缺失：
#'
#' * R原生缺失值：`NA`，包括数值型 `NaN`；
#' * 空字符串或仅包含空格的字符串；
#' * `"NA"`；
#' * `"NULL"`；
#' * `"N/A"`；
#' * `"NaN"`；
#' * `"."`；
#' * `"*"`；
#' * `"/"`。
#'
#' 字符型缺失编码不区分大小写，例如 `"na"`、`"null"`
#' 也会被识别为缺失。函数仅去除字符串首尾的空格，例如
#' `" NA "` 和 `". "` 均会被识别为缺失；
#' 字符串中间的空格不会被去除，例如 `"N A"` 不会被识别为 `"NA"`。
#'
#' `"N"` 及 `"n"` 不会被识别为缺失值。
#'
#' @examples
#' x <- c(NA, "", " ", "N", "NA", "NULL", "N/A", "NaN", ".", "*", "/", "Yes")
#' is_miss(x)
#'
#' @export
is_miss <- function(x) {

  # 定义字符型缺失编码，不包括N
  na_strings <- c("", "NA", "NULL", "N/A", "NaN", ".", "*", "/")

  # 统一判断R原生缺失值和字符型缺失编码
  is.na(x) | toupper(trimws(x)) %in% toupper(na_strings)
}
